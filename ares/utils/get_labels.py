from ares.interface.data.ares_signal import AresSignal
from ares.interface.parameter.ares_parameter import AresParameter
from ares.utils.decorators import typechecked_dev as typechecked


@typechecked
def get_labels(
    base_type_list: list[AresSignal | AresParameter],
) -> list[str]:
    """Return the label of each signal or parameter in the input list.

    Args:
        base_type_list (list[AresSignal | AresParameter]): Signals and/or
            parameters whose labels should be collected.

    Returns:
        list[str]: Labels in the same order as the input objects.
    """
    return [base_type_list.label for base_type_list in base_type_list]
